"""Builds include/ecu_profiles.h, the stand-alone PCB firmware's ECU table, from the Frogdash
dash's ECU profiles (hardware/frogdash/ecu/profiles/*.json in averyizatt/frogdash), and the
host test's vectors (test/test_ecu_profiles/vectors.h) from the dash's own decoder.

Only what injection needs is taken from each profile: engine speed, manifold pressure,
barometric pressure and intake air temperature. The dash's profiles name their sources
(each manufacturer's published CAN document) and say how far each has been checked; the
table keeps that status, and the web page shows it.

    python tools/ecu_profiles.py ../../frogdash

Run it again whenever the dash's profiles change, and commit both files.
"""
import json
import random
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]
FIELDS = {'ecu.rpm': 'Rpm', 'ecu.map_kpa': 'MapKpa', 'ecu.baro_kpa': 'BaroKpa', 'ecu.iat_c': 'IatC'}
LAYOUTS = {'u8': ('U8', 1), 's8': ('S8', 1), 'u16': ('U16Be', 2), 's16': ('S16Be', 2), 'u16le': ('U16Le', 2),
           's16le': ('S16Le', 2), 'u32': ('U32Be', 4), 's32': ('S32Be', 4), 'u32le': ('U32Le', 4),
           's32le': ('S32Le', 4), 'f32': ('F32Be', 4), 'f32le': ('F32Le', 4)}
CONVERTS = {None: 'None', 'degF_tenths_to_C': 'DegFTenthsToC', 'degF_to_C': 'DegFToC'}
FROM = {None: 'None', 'degF': 'DegFToC', 'K': 'KelvinToC', 'psi': 'PsiToKpa', 'bar': 'BarToKpa'}
SKIP = ('obd2', 'obd2_29bit')   # Polled, not broadcast: engine_source.h has its own OBD-II poller.


def number(text):
    return text if isinstance(text, int) else int(text, 0)


def cpp_float(value):
    text = repr(float(value))
    return text if ('.' in text or 'e' in text) else text + '.0'


def load(frogdash):
    folder = frogdash / 'hardware' / 'frogdash' / 'ecu' / 'profiles'
    profiles = []
    for path in sorted(folder.glob('*.json')):
        if path.stem in SKIP:
            continue
        data = json.loads(path.read_text(encoding='utf-8'))
        base = number(data['base']['default']) if data.get('base') else 0
        signals = []
        for frame in data.get('frames') or []:
            ids = [(number(i), False) for i in frame.get('ids') or []]
            ids += [(number(o), True) for o in frame.get('offsets') or []]
            for spec in frame.get('signals') or []:
                field = FIELDS.get(spec['key'])
                if not field:
                    continue
                kind, byte = spec['layout'].split('@')
                if kind not in LAYOUTS:
                    sys.exit(f'{path.name}: layout {spec["layout"]} is not one the firmware reads')
                if spec.get('convert') not in CONVERTS or spec.get('from') not in FROM:
                    sys.exit(f'{path.name}: conversion {spec.get("convert") or spec.get("from")} is not one the firmware has')
                convert = CONVERTS[spec.get('convert')] if spec.get('convert') else FROM[spec.get('from')]
                for ident, relative in ids:
                    signals.append(dict(id=ident, relative=relative, field=field, layout=LAYOUTS[kind][0],
                                        size=LAYOUTS[kind][1], byte=int(byte), scale=spec.get('scale', 1),
                                        offset=spec.get('offset', 0), convert=convert, spec=spec,
                                        length=frame.get('length', 8)))
        if not any(s['field'] == 'Rpm' for s in signals) or not any(s['field'] == 'MapKpa' for s in signals):
            print(f'{path.stem}: no engine speed or manifold pressure; left out')
            continue
        profiles.append(dict(id=path.stem, label=data.get('label', path.stem), bitrate=data.get('bitrate', 500000),
                             extended=bool(data.get('extended')), mask=number(data['id_mask']) if data.get('id_mask') else 0,
                             base=base, status=data.get('status', 'documented'), signals=signals,
                             source=(data.get('source') or {}).get('title', '')))
    return profiles


def header(profiles):
    out = ['#pragma once', '',
           '// Generated by tools/ecu_profiles.py from the Frogdash dash\'s ECU profiles',
           '// (averyizatt/frogdash hardware/frogdash/ecu/profiles): do not edit by hand.',
           '// Engine speed, manifold pressure, barometric pressure and intake air temperature',
           '// from each ECU\'s published CAN broadcast, for the stand-alone PCB firmware',
           '// (engine_source.h reads them).',
           '#include "engine_source_types.h"', '', 'namespace engine {', '']
    for p in profiles:
        out.append(f'// {p["label"]}: {p["source"]}' if p['source'] else f'// {p["label"]}')
        out.append(f'constexpr Signal k{camel(p["id"])}Signals[] = {{')
        for s in p['signals']:
            out.append(f'    {{0x{s["id"]:X}, {"true" if s["relative"] else "false"}, Field::{s["field"]}, Layout::{s["layout"]}, '
                       f'{s["byte"]}, {cpp_float(s["scale"])}, {cpp_float(s["offset"])}, Convert::{s["convert"]}}},')
        out.append('};')
    out.append('')
    out.append('constexpr Profile kProfiles[] = {')
    for p in profiles:
        out.append(f'    {{"{p["id"]}", "{p["label"]}", {p["bitrate"]}UL, {"true" if p["extended"] else "false"}, '
                   f'0x{p["mask"]:X}UL, 0x{p["base"]:X}UL, "{p["status"]}", k{camel(p["id"])}Signals, '
                   f'sizeof(k{camel(p["id"])}Signals) / sizeof(Signal)}},')
    out.append('};')
    out.append('constexpr uint8_t kProfileCount = sizeof(kProfiles) / sizeof(Profile);')
    out += ['', '} // namespace engine', '']
    return '\n'.join(out)


def camel(name):
    return ''.join(part.capitalize() for part in name.replace('-', '_').split('_'))


def vectors(profiles, frogdash):
    """Random frames for every signal, decoded by the dash's own code."""
    sys.path.insert(0, str(frogdash / 'hardware'))
    from frogdash.ecu import Profile  # noqa: E402  (the dash's decoder)
    rng = random.Random(20261118)
    folder = frogdash / 'hardware' / 'frogdash' / 'ecu' / 'profiles'
    lines = ['#pragma once', '// Generated by tools/ecu_profiles.py: frames decoded by the Frogdash dash\'s own',
             '// decoder (hardware/frogdash/ecu), for test_ecu_profiles. Do not edit by hand.',
             '#include <stdint.h>', '', 'struct Vector {', '  uint8_t profile;', '  uint32_t id;', '  uint8_t data[8];',
             '  const char *key;', '  double value;', '};', '', 'const Vector kVectors[] = {']
    count = 0
    for index, p in enumerate(profiles):
        dash = Profile(json.loads((folder / f'{p["id"]}.json').read_text(encoding='utf-8')), 'test')
        for s in p['signals']:
            ident = (p['base'] + s['id']) if s['relative'] else s['id']
            if p['mask']:
                ident |= rng.randrange(0, (~p['mask']) & 0x7FF)   # Serial bits the mask takes off
            for _ in range(6):
                data = bytes(rng.randrange(256) for _ in range(8))
                if s['layout'].startswith('F32'):
                    value = rng.uniform(-50, 9000)
                    packed = struct.pack('<f' if s['layout'] == 'F32Le' else '>f', value)
                    data = data[:s['byte']] + packed + data[s['byte'] + 4:]
                decoded = dash.decode(ident, data)
                key = s['spec']['key']
                if key not in decoded:
                    sys.exit(f'{p["id"]}: the dash does not decode {key} from 0x{ident:X}')
                lines.append(f'    {{{index}, 0x{ident:X}, {{{", ".join(f"0x{b:02X}" for b in data)}}}, "{key}", '
                             f'{decoded[key]!r}}},')
                count += 1
    lines += ['};', f'constexpr unsigned kVectorCount = {count};', '']
    return '\n'.join(lines)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    frogdash = Path(sys.argv[1]).resolve()
    profiles = load(frogdash)
    (HERE / 'include' / 'ecu_profiles.h').write_text(header(profiles), encoding='utf-8', newline='\n')
    target = HERE / 'test' / 'test_ecu_profiles'
    target.mkdir(exist_ok=True)
    (target / 'vectors.h').write_text(vectors(profiles, frogdash), encoding='utf-8', newline='\n')
    print(f'{len(profiles)} profiles: {", ".join(p["id"] for p in profiles)}')


if __name__ == '__main__':
    main()
